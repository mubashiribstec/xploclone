# XploClone — one-click install (Windows, PowerShell 5.1+).
#
#   .\install.ps1            # auto-detect: GPU if nvidia-smi works, else CPU
#   .\install.ps1 -Mode cpu  # CPU mode (Chatterbox Nano, file generation only)
#   .\install.ps1 -Mode gpu  # GPU mode (Chatterbox Turbo, CUDA 13.0)
#   .\install.ps1 -CheckOnly # preflight checks only, no changes
#
# Same behaviour as install.sh: checks Docker + Compose, checks for an
# NVIDIA GPU (warns, does not fail, if none), creates .env with fresh
# random secrets (API key + hash, web password hash + session secret),
# prints the web password ONCE, then runs the right compose profile
# and waits for /health.
#
# NOT tested on Windows in this environment (no Windows host here) —
# the Linux install.sh is the tested path. If this script fails on
# your machine, follow docs/INSTALL.md (manual install) and report
# the exact error. Requires Docker Desktop with WSL 2.
param(
  [ValidateSet("auto", "cpu", "gpu")]
  [string]$Mode = "auto",
  [switch]$CheckOnly,
  [switch]$DryRun
)
$ErrorActionPreference = "Stop"
Set-Location $PSScriptRoot

function Log($m) { Write-Host "[xploclone] $m" }
function Warn($m) { Write-Host "[xploclone] WARNING: $m" -ForegroundColor Yellow }

function HexSecret($bytes) {
  $b = New-Object byte[] $bytes
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
  -join ($b | ForEach-Object { $_.ToString("x2") })
}
function Sha256Hex($text) {
  $sha = [System.Security.Cryptography.SHA256]::Create()
  $bytes = [System.Text.Encoding]::UTF8.GetBytes($text)
  -join ($sha.ComputeHash($bytes) | ForEach-Object { $_.ToString("x2") })
}

Log "Preflight checks"
if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
  Write-Host "[xploclone] ERROR: Docker is not installed. Install Docker Desktop, then re-run." -ForegroundColor Red
  exit 1
}
Log ("Docker: " + (docker --version))
try { docker compose version | Out-Null; $compose = "docker compose" } catch { Write-Host "[xploclone] ERROR: Docker Compose not found." -ForegroundColor Red; exit 1 }
Log "Compose: $compose"

$hasGpu = $false
try { nvidia-smi -L | Out-Null; $hasGpu = $true; Log "NVIDIA GPU detected." } catch { Warn "No NVIDIA GPU detected. GPU mode will fail; CPU mode is the fallback." }
if ($Mode -eq "auto") { $Mode = if ($hasGpu) { "gpu" } else { "cpu" }; Log "Mode auto-detected: $Mode" } else { Log "Mode: $Mode" }
if ($CheckOnly) { Log "check-only: nothing was changed."; exit 0 }

$webPassword = ""
if (-not (Test-Path .env)) {
  Log "Creating .env with fresh random secrets..."
  $apiKey = HexSecret 32
  $webPassword = HexSecret 8
  $engine = if ($Mode -eq "cpu") { "nano" } else { "turbo" }
  $device = if ($Mode -eq "cpu") { "cpu" } else { "cuda" }
  $threads = if ($Mode -eq "cpu") { "8" } else { "0" }
  $date = (Get-Date -Format "yyyy-MM-dd")
  @"
# XploClone — generated by install.ps1 on $date. NEVER commit .env.
XPLOCLONE_API_KEY=$apiKey
XPLOCLONE_API_KEY_HASH=$(Sha256Hex $apiKey)
XPLOCLONE_DEVICE=$device
XPLOCLONE_ENGINE=$engine
XPLOCLONE_TORCH_THREADS=$threads
XPLOCLONE_REF_DIR=api/reference
XPLOCLONE_CHATTERBOX_REVISION=749d1c1a46eb10492095d68fbcf55691ccf137cd
XPLOCLONE_CHATTERBOX_NANO_REVISION=
XPLOCLONE_RATE_LIMIT_PER_MIN=60
XPLOCLONE_QUEUE_MAX=10
XPLOCLONE_REQUEST_TIMEOUT_S=30
XPLOCLONE_MAX_CHARS=5000
XPLOCLONE_API_URL=http://localhost:8000
XPLOCLONE_WEB_PASSWORD_HASH=$(Sha256Hex $webPassword)
XPLOCLONE_WEB_SESSION_SECRET=$(HexSecret 32)
"@ | Out-File -FilePath .env -Encoding utf8
  Log ".env created. Web password is printed once below — save it now."
} else {
  Log ".env already exists — keeping it (never overwriting secrets)."
}
New-Item -ItemType Directory -Force -Path api\reference | Out-Null

if ($DryRun) {
  if ($Mode -eq "cpu") { Log "[dry-run] would run: docker compose -f docker-compose.yml -f docker-compose.cpu.yml up --build -d" }
  else { Log "[dry-run] would run: docker compose -f docker-compose.yml up --build -d" }
  exit 0
}

if ($Mode -eq "cpu") { docker compose -f docker-compose.yml -f docker-compose.cpu.yml up --build -d }
else { docker compose -f docker-compose.yml up --build -d }

Log "Waiting for the API (up to 180 s)..."
for ($i = 0; $i -lt 36; $i++) {
  try { Invoke-RestMethod http://127.0.0.1:8000/health -TimeoutSec 5 | Out-Null; Log "API is up."; break } catch { Start-Sleep 5 }
}
Write-Host ""
Log "Done. Mode: $Mode"
Log "Web UI:  http://localhost:3000/login"
Log "API:     http://127.0.0.1:8000/health"
if ($webPassword) {
  Write-Host ""
  Write-Host "  *** SAVE THIS — it is printed once and never stored in plaintext ***"
  Write-Host "  Web UI password: $webPassword"
  Write-Host ""
}
Log "Next: place reference clips in api/reference/, then restart: docker compose restart api"
